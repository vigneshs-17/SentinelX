"""Copy the Phase 4 eval report and the ML gate decision into README.md between the RESULTS markers.

Usage: python main.py eval --scenarios all --out eval_output && python scripts/gen_readme_results.py [run/report.json ...]
No number is typed by hand: tables come from eval_output/report.md, the ML decision from docs/ML_REPORT.md.
Throughput is machine-dependent, so one figure misleads: pass the report.json of each repeated run (for example three
separate `main.py eval --out eval_runN` runs) and the README shows min-max over them. With no arguments it uses
eval_output/report.json alone and says it is a single run.
"""

from __future__ import annotations

import json
import re
import subprocess  # nosec B404
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
REPORT = ROOT / "eval_output" / "report.md"
ML_REPORT = ROOT / "docs" / "ML_REPORT.md"
BEGIN, END = "<!-- RESULTS:BEGIN (generated by scripts/gen_readme_results.py) -->", "<!-- RESULTS:END -->"
COMMAND = "python main.py eval --scenarios all --out eval_output"


def _git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, check=False).stdout.strip()  # nosec B603 B607


def throughput_range(report_jsons: list[Path]) -> str:
    """'min-max packets/sec (N runs)' from the throughput_pps of each report.json."""
    values = [float(json.loads(p.read_text(encoding="utf-8"))["throughput_pps"]) for p in report_jsons]
    if len(values) == 1:
        return f"{values[0]:,.0f} packets/sec (1 run; machine-dependent)"
    return f"{min(values):,.0f}-{max(values):,.0f} packets/sec (min-max of {len(values)} runs; machine-dependent)"


def render(report_jsons: list[Path] | None = None) -> str:
    report = REPORT.read_text(encoding="utf-8")
    start = report.index("**Benchmark Status**")
    body = report[start:].split("\n> [!NOTE]")[0].rstrip()
    body, n = re.subn(
        r"\*\*Throughput\*\*: [\d,.]+ packets/sec",
        "**Throughput**: " + throughput_range(report_jsons or [ROOT / "eval_output" / "report.json"]),
        body,
    )
    if n != 1:
        raise SystemExit("could not find the Throughput line in eval_output/report.md")
    body = re.sub(r"^## ", "#### ", body, flags=re.M)
    decision = re.search(r"\*\*Decision: ([^*]+)\*\*", ML_REPORT.read_text(encoding="utf-8"))
    sha = _git("rev-parse", "HEAD")
    dirty = " plus uncommitted changes" if _git("status", "--porcelain") else ""
    return "\n".join(
        [
            BEGIN,
            "",
            f"Command: `{COMMAND}`  ",
            f"Commit: `{sha}`{dirty}. Machine-dependent numbers (throughput, wall-clock) are from the machine that ran it.",
            "",
            body,
            "",
            f"ML gate (`docs/ML_REPORT.md`): **{decision.group(1) if decision else 'unknown'}**",
            "",
            END,
        ]
    )


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    text = README.read_text(encoding="utf-8")
    a, b = text.index(BEGIN), text.index(END) + len(END)
    README.write_text(text[:a] + render([Path(x) for x in args] or None) + text[b:], encoding="utf-8")
    print("README results block updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
